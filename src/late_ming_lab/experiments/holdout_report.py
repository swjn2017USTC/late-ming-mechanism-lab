"""The V2-P04 documents: what each V1 failure turned out to be, and what the structures produced.

Written by `late-ming-lab experiment p04`, never hand-edited: the diagnosis document carries its
generator in the header and is rewritten from the runs each time, like the other generated docs
under `docs/v2/`.

Two documents, one argument:

```text
docs/v2/hold-out-diagnosis.md     per failure: the class it falls in, the numbers read from
                                  the reference run, and the boundary that stays open; then the
                                  structural comparison — what each arm moved, and what it did not
docs/v2/hold-out-diagnosis.json   the same, machine-readable, with every run's identity
```

The rules the document follows are the phase's own: a failure is classified from evidence and not
from convenience, a structural arm has to prove it intervened, and no reserved window is used to
choose a structure.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Final

from late_ming_lab.experiments.holdout import (
    FAILED_CHECKS,
    HOLDOUT_SEEDS,
    REFERENCE_ARM,
    V1_RECORDED_SOURCE,
    ArmRun,
    FailureDiagnosis,
    _moved_facts,
    detect_no_op,
    diagnosis_table,
    window_checks,
)

#: Where the generated documents live, and what wrote them.
DIAGNOSIS_DOCUMENT: Final[str] = "docs/v2/hold-out-diagnosis.md"
DIAGNOSIS_JSON: Final[str] = "docs/v2/hold-out-diagnosis.json"
GENERATOR: Final[str] = "late-ming-lab experiment p04"

#: The classifications a failure may be given, and what each one means.
CLASSIFICATIONS: Final[dict[str, str]] = {
    "data": "the input the model was handed, not the mechanism that read it",
    "observation": "the quantity the check reads, rather than the process it reads it from",
    "parameter": "a declared number the model was given",
    "structure": "a mechanism the model lacks, or has in a form that cannot produce the pattern",
    "undetermined": "nothing this model currently measures can decide it",
}


def write_documents(
    root: str | Path,
    runs: Sequence[ArmRun],
    *,
    generator: str = GENERATOR,
    scores: dict[str, dict[str, object]] | None = None,
) -> tuple[Path, Path]:
    """Write the diagnosis document and its machine-readable twin; return both paths."""
    repository = Path(root)
    document = repository / DIAGNOSIS_DOCUMENT
    machine = repository / DIAGNOSIS_JSON
    document.parent.mkdir(parents=True, exist_ok=True)
    runs = tuple(runs)
    reference = next(run for run in runs if run.arm.label == REFERENCE_ARM)
    entries = diagnosis_table(runs, root=repository)
    diagnosis = {entry.pattern: entry for entry in entries}
    no_op_report = detect_no_op(tuple(runs))
    checks = {run.facts.run_id: window_checks(run.events, registry_root=repository) for run in runs}
    machine.write_text(
        json.dumps(
            {
                "generator": generator,
                "seeds": list(HOLDOUT_SEEDS),
                "diagnosis": [entry.model_dump(mode="json") for entry in entries],
                "no_op_check": list(no_op_report),
                "protocol_scores": scores or {},
                "arms": [
                    {
                        "arm": run.arm.label,
                        "description": run.arm.description,
                        "expects_effect": run.arm.expects_effect,
                        "configuration_diff": run.arm.configuration_diff(),
                        "run_id": run.facts.run_id,
                        "root_seed": run.facts.root_seed,
                        "simulation_digest": run.facts.simulation_digest,
                        "event_total": run.facts.event_total,
                        "event_counts": run.facts.event_counts,
                        "chains": run.facts.chains,
                        "checks": checks[run.facts.run_id],
                    }
                    for run in runs
                ],
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    document.write_text(
        _markdown(
            runs=runs,
            reference=reference,
            diagnosis=diagnosis,
            no_op_report=no_op_report,
            checks=checks,
            scores=scores or {},
        ),
        encoding="utf-8",
    )
    return document, machine


def _markdown(
    *,
    runs: tuple[ArmRun, ...],
    reference: ArmRun,
    diagnosis: dict[str, FailureDiagnosis],
    no_op_report: tuple[str, ...],
    checks: dict[str, dict[str, dict[str, float]]],
    scores: dict[str, dict[str, object]],
) -> str:
    lines = [
        f"<!-- generated by: {GENERATOR} -->",
        "",
        "# What the V1 hold-out failures were",
        "",
        f"Generated by `{GENERATOR}` over `docs/v2/hold-out-diagnosis.json`. Do not edit: the",
        "command rewrites this file.",
        "",
        "**A failure is not a result until it is attributed.** Each of the four V1 failures below",
        "is classified as a data, observation, parameter or structure problem — or as undetermined",
        "— with the numbers the reference run produced beside it, and with the boundary that stays",
        "open after the phase. The classification is an argument: a reader who disagrees can read",
        "the same numbers in the JSON beside this file.",
        "",
        "## The four failures",
        "",
        "| pattern | check | read on | classification | means |",
        "| --- | --- | --- | --- | --- |",
    ]
    for pattern, check, surface in FAILED_CHECKS:
        entry = diagnosis[pattern]
        classification = entry.classification
        lines.append(
            f"| `{pattern}` | `{check}` | {surface} | **{classification}** | "
            f"{CLASSIFICATIONS.get(classification, '')} |"
        )
    for pattern, check, surface in FAILED_CHECKS:
        entry = diagnosis[pattern]
        lines += [
            "",
            f"### `{pattern}` — {entry.classification}",
            "",
            f"The check is `{check}`, read on {surface}. V1 recorded these shares "
            f"({V1_RECORDED_SOURCE}):",
            "",
            "| window | satisfied share |",
            "| --- | --- |",
        ]
        for window_id, share in entry.v1_recorded.items():
            lines.append(f"| {window_id} | {share:.2f} |")
        if entry.reference_checks:
            lines += [
                "",
                "This phase's reference run, scored by the same prediction code:",
                "",
                "| window | value | satisfied |",
                "| --- | --- | --- |",
            ]
            for window_id, score in entry.reference_checks.items():
                if not score:
                    continue
                lines.append(f"| {window_id} | {score['value']:.4f} | {score['satisfied']:.0f} |")
        else:
            lines += [
                "",
                "The check is a calibration-window mismatch, and the prediction path refuses that",
                "window: V2-P03's isolation is not suspended to re-score it here. What this phase",
                "adds is the chain behind it, below.",
            ]
        lines += [
            "",
            "What the reference run on the historical core shows:",
            "",
            "| fact | value |",
            "| --- | --- |",
        ]
        for name, value in entry.evidence.items():
            lines.append(f"| `{name}` | {_format(value)} |")
        lines += ["", f"**Boundary that stays open:** {entry.boundary}", ""]
    lines += [
        "## The structural comparison",
        "",
        f"Every arm ran on `historical-core-v1` at the same {len(HOLDOUT_SEEDS)} world seeds: "
        f"{', '.join(str(seed) for seed in HOLDOUT_SEEDS)}.",
        "",
        "| arm | declares a change | what it moved against the reference |",
        "| --- | --- | --- |",
    ]
    reference_by_seed = {run.facts.root_seed: run for run in runs if run.arm.label == REFERENCE_ARM}
    for run in runs:
        if run.facts.root_seed != HOLDOUT_SEEDS[0]:
            continue
        if run.arm.label == REFERENCE_ARM:
            lines.append(f"| `{run.arm.label}` | {run.arm.description} | — the reference |")
            continue
        baseline = reference_by_seed[run.facts.root_seed]
        moved = sorted(_moved_facts(baseline.facts, run.facts))
        lines.append(
            f"| `{run.arm.label}` | {'yes' if run.arm.expects_effect else 'no (ablation)'} | "
            f"{', '.join(moved) if moved else 'nothing: identical to the reference'} |"
        )
    lines += [
        "",
        "### The no-op check",
        "",
        "An arm that declares a structure and moves nothing fails the phase; an ablation that",
        "moves something means the parameter is not what carries the intervention. The detector's",
        "verdict for every arm, on every declared seed:",
        "",
        *[f"- {line}" for line in no_op_report],
        "",
        "### The reserved windows, reported and not optimised",
        "",
        "The checks V1 failed, per arm, first seed. These numbers never select an arm: a",
        "structure is chosen on the evidence its failure points at, and the hold-out tests it.",
        "",
        "| arm | check | value | satisfied |",
        "| --- | --- | --- | --- |",
    ]
    for run in runs:
        if run.facts.root_seed != HOLDOUT_SEEDS[0]:
            continue
        scored = checks[run.facts.run_id]
        for _pattern, check, _surface in FAILED_CHECKS:
            for window_id in ("hold-out", "extrapolation"):
                key = f"{window_id}.{check}"
                if key not in scored:
                    continue
                value = scored[key]["value"]
                satisfied = scored[key]["satisfied"]
                lines.append(f"| `{run.arm.label}` | {key} | {value:.4f} | {satisfied:.0f} |")
    if scores:
        lines += [
            "",
            "## Scored under the frozen protocol",
            "",
            "Each arm's whole-run outcome vector as V2-P03's protocol defines it, and the share ",
            "of the",
            "50,625-member threshold ensemble under which the run reads as in breakdown at the",
            "protocol's declared line. The protocol's mechanism criteria are bound to V2-P03's own",
            "pilot arms, so on these runs the ones needing an arm contrast report `undetermined`:",
            "that is printed as the answer rather than re-pointed at whichever arm looks closest.",
            "",
            "| arm | outcome | value |",
            "| --- | --- | --- |",
        ]
        for run in runs:
            if run.facts.root_seed != HOLDOUT_SEEDS[0]:
                continue
            arm_score = scores.get(run.facts.run_id)
            if not arm_score:
                continue
            outcomes = arm_score["outcomes"]
            assert isinstance(outcomes, dict)
            for name in sorted(outcomes):
                value = outcomes[name]
                assert isinstance(value, dict)
                rendered = value.get("value")
                shown = "—" if rendered is None else f"{float(rendered):.6g}"
                lines.append(f"| `{run.arm.label}` | `{name}` | {shown} |")
        lines += [
            "",
            "| arm | breakdown share (line 6) | crossed count distribution |",
            "| --- | --- | --- |",
        ]
        for run in runs:
            if run.facts.root_seed != HOLDOUT_SEEDS[0]:
                continue
            arm_score = scores.get(run.facts.run_id)
            if not arm_score:
                continue
            shares = arm_score["breakdown_shares"]
            assert isinstance(shares, dict)
            crossed = arm_score["crossed_count_share"]
            assert isinstance(crossed, dict)
            distribution = ", ".join(
                f"{count}:{share:.3f}"
                for count, share in sorted(crossed.items(), key=lambda item: int(item[0]))
            )
            lines.append(f"| `{run.arm.label}` | {shares.get('6', 0.0):.3f} | {distribution} |")
    lines += [
        "",
        "## What this document does not say",
        "",
        "- It does not say the structures are right. They are declared answers to what the",
        "  failures point at, and every parameter they add is grade `S`, entering the V2 pool.",
        "- It does not re-adjudicate V1's mechanism cards: their evidence is the P10 and P12",
        "  arms, and a criterion scored on these arms is a statement about these arms.",
        "- It does not claim a historical magnitude. The price chain's ceiling is a declared",
        "  ratio, so what can be asked is which constraint bound and how far, not whether it",
        "  reaches a recorded famine price.",
        "",
    ]
    return "\n".join(lines)


def _format(value: object) -> str:
    if isinstance(value, float):
        return f"{value:.6g}"
    if isinstance(value, dict):
        return ", ".join(f"{name}={_format(item)}" for name, item in sorted(value.items())) or "—"
    if value is None:
        return "—"
    return str(value)
